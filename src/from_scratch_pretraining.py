import time

MAX_STEPS = 10000
EVAL_INTERVAL = 500
EVAL_ITERS = 50
WARMUP_STEPS = 200
LEARNING_RATE = 6e-4
MIN_LR = 6e-5

optimizer = torch.optim.AdamW(model.parameters(), lr=LEARNING_RATE, weight_decay=0.1, betas=(0.9, 0.95))
scaler = torch.amp.GradScaler('cuda')

# Learning rate schedule with linear warmup and cosine decay
def get_lr(step):
    if step < WARMUP_STEPS:
        return LEARNING_RATE * (step + 1) / (WARMUP_STEPS + 1)
    if step > MAX_STEPS:
        return MIN_LR
    decay_ratio = (step - WARMUP_STEPS) / (MAX_STEPS - WARMUP_STEPS)
    coeff = 0.5 * (1.0 + math.cos(math.pi * decay_ratio))
    return MIN_LR + coeff * (LEARNING_RATE - MIN_LR)

@torch.no_grad()
def estimate_loss():
    out = {}
    model.eval()
    for split in ['train', 'val']:
        losses = torch.zeros(EVAL_ITERS)
        for k in range(EVAL_ITERS):
            X, Y = get_batch(split)
            with torch.amp.autocast('cuda', dtype=torch.float16):
                _, loss = model(X, Y)
            losses[k] = loss.item()
        out[split] = losses.mean()
    model.train()
    return out

print("Starting training on T4 GPU...")
start_time = time.time()

for step in range(MAX_STEPS):
    # Set dynamic learning rate
    lr = get_lr(step)
    for param_group in optimizer.param_groups:
        param_group['lr'] = lr

    # Periodic evaluation & sample generation
    if step % EVAL_INTERVAL == 0 or step == MAX_STEPS - 1:
        losses = estimate_loss()
        elapsed = time.time() - start_time
        print(f"\n--- Step {step} | Train Loss: {losses['train']:.4f} | Val Loss: {losses['val']:.4f} | Elapsed: {elapsed/60:.1f}m ---")

        # Generate a live preview
        preview = model.generate("Once upon a time, a little girl named Lily found", max_new_tokens=80)
        print(f"Sample output:\n{preview}\n")

        # Save checkpoint to Google Drive
        ckpt_path = os.path.join(checkpoint_dir, f"model_step_{step}.pt")
        torch.save({
            'step': step,
            'model_state_dict': model.state_dict(),
            'optimizer_state_dict': optimizer.state_dict(),
            'val_loss': losses['val'],
        }, ckpt_path)

    # Standard forward/backward with mixed precision
    xb, yb = get_batch('train')
    optimizer.zero_grad(set_to_none=True)

    with torch.amp.autocast('cuda', dtype=torch.float16):
        logits, loss = model(xb, yb)

    scaler.scale(loss).backward()
    scaler.unscale_(optimizer)
    torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=1.0)
    scaler.step(optimizer)
    scaler.update()

print("Training complete! Final checkpoint saved to Google Drive.")

