def get_continuation_lr(step):

    progress = (
        (step - start_step)
        / (RESUME_TO_STEP - start_step)
    )

    progress = max(
        0.0,
        min(1.0, progress)
    )

    return (
        START_LR
        + progress
        * (END_LR - START_LR)
    )


